// Ports the hero drawing of the style prototype (docs/reference/style-test.html) into the game:
//   node scripts/port-proto.mjs            (also: npm run port:proto)
// It takes drawHuman and everything it needs (helpers, SWING, hero defs, resolve) by following
// the top level declarations of the prototype's script, and writes
//   src/ui/parts/proto.gen.ts   (drawing code, not edited by hand)
//   src/data/heroParts.gen.ts   (the hero defs: colours, heads, gear, tier 2 and 3 overlays)
// so a new prototype is one command away from the game. The page-only parts (DOM, canvas
// setup, ground, units, AI) are left out; the few globals the drawing reads are set through
// `setState`.
import { readFileSync, writeFileSync } from 'node:fs';

const SRC = 'docs/reference/style-test.html';
const OUT = 'src/ui/parts/proto.gen.ts';
const OUT_DATA = 'src/data/heroParts.gen.ts';
const html = readFileSync(SRC, 'utf8');
const script = html.slice(html.indexOf('<script>') + 8, html.lastIndexOf('</script>'));
const lines = script.split('\n');

// Globals the page sets up itself: declared by hand in the output.
const MANUAL = new Set([
  'cv',
  'ctx',
  'T',
  'speed',
  'paused',
  'zoom',
  'showRings',
  'showNames',
  'K',
  'SEL',
  'FL',
  'TINT',
  'TA',
  'LX',
]);

// Page arrays whose names also appear as locals in the drawing (`const fx = ...`): never follow.
for (const n of ['parts', 'nums', 'shots', 'fx', 'units', 'heroes']) MANUAL.add(n);

// Top level declarations are the lines indented by exactly two spaces.
const decls = [];
let cur = null;
for (let i = 0; i < lines.length; i++) {
  const l = lines[i];
  const m = /^ {2}(function|const|let)\s+([A-Za-z_$][\w$]*)/.exec(l);
  const isTop = /^ {2}\S/.test(l) && !/^ {2}[)}\]]/.test(l);
  if (m) {
    cur = { kind: m[1], names: [m[2]], start: i, end: i };
    decls.push(cur);
    if (m[1] !== 'function') {
      // `const a = 1,\n    b = 2;` declares more names on 4 space lines
      for (let j = i + 1; j < lines.length && !/^ {2}\S/.test(lines[j]); j++) {
        const mm = /^ {4}([A-Za-z_$][\w$]*)\s*=/.exec(lines[j]);
        if (mm) cur.names.push(mm[1]);
      }
    }
  } else if (cur && isTop && !/^ {2}\/\//.test(l)) {
    cur = null;
  } else if (cur) cur.end = i;
}
// trim trailing comment / blank lines belonging to the next declaration
for (const d of decls) {
  while (d.end > d.start && (/^\s*$/.test(lines[d.end]) || /^ {2}\/\//.test(lines[d.end]))) d.end--;
  d.text = lines.slice(d.start, d.end + 1).join('\n');
}
const byName = new Map();
for (const d of decls) for (const n of d.names) byName.set(n, d);

// Follow identifiers from the roots.
const ROOTS = ['drawHuman', 'SWING', 'raven'];
const DATA = new Set(['HERO_DEFS', 'SWING']);
const need = new Set();
const todo = [...ROOTS];
while (todo.length) {
  const n = todo.pop();
  const d = byName.get(n);
  if (!d || need.has(d) || MANUAL.has(n)) continue;
  need.add(d);
  if (DATA.has(n)) continue; // pure data: its keys are not references
  const body = d.text.replace(/\/\/.*$/gm, '');
  for (const id of new Set(body.match(/(?<![.\w$])[A-Za-z_$][\w$]*/g) ?? [])) {
    if (byName.has(id) && !MANUAL.has(id)) {
      if (process.env.TRACE && !need.has(byName.get(id))) console.log(`${d.names[0]} -> ${id}`);
      todo.push(id);
    }
  }
}
const picked = decls.filter((d) => need.has(d)).sort((a, b) => a.start - b.start);
const heroDefs = byName.get('HERO_DEFS');
const monDefs = byName.get('MON_DEFS');

// A page-only reference left in the closure means the closure grew too far: say so.
const bad = picked.filter((d) =>
  /\b(document|window|cv\b|requestAnimationFrame|units\b|parts\b|nums\b)/.test(d.text),
);
if (bad.length)
  throw new Error(`page-only code in the closure: ${bad.map((d) => d.names.join(',')).join('; ')}`);

const body = picked.map((d) => d.text).join('\n');
const out = `/* eslint-disable */
// @ts-nocheck
// GENERATED by scripts/port-proto.mjs from ${SRC}. Do not edit by hand: change the prototype and
// run \`npm run port:proto\`. The prototype's hero drawing, mirrored one to one.
let ctx = null;
let T = 0,
  FL = 0,
  TINT = null,
  TA = 0,
  LX = 1,
  K = 1,
  SEL = { t: 1, p: 0 },
  speed = 1,
  zoom = 1;

// The page globals the drawing reads (the canvas context, the clock, the hit flash, the tint).
export function setState(s) {
  if ('ctx' in s) ctx = s.ctx;
  if ('T' in s) T = s.T;
  if ('FL' in s) FL = s.FL;
}

${body}

export { drawHuman, pose, usc, SWING };
`;
writeFileSync(OUT, out);
console.log(`${OUT}: ${picked.length} declarations, ${out.split('\n').length} lines`);

const data = `// GENERATED by scripts/port-proto.mjs from ${SRC}. Do not edit by hand: change the prototype and
// run \`npm run port:proto\`. A path never swaps the hero: tier 2 adds gear and effects on top of
// tier 1, tier 3 adds more of the same path (src/data/heroParts.ts picks and merges them).
export ${heroDefs.text.trim().replace(/^ *lead: true,\n/gm, '')}

// The monsters of the prototype on the same compact rig (src/data/monsterParts.ts decides which
// game monster uses which row). hp, speed and atk here are display only: sim stats live in src/data.
export ${monDefs.text.trim()}
`;
writeFileSync(OUT_DATA, data);
console.log(`${OUT_DATA}: ${data.split('\n').length} lines`);
